-- actualizar refugio
create or replace procedure sp_actualizar_refugio(
    p_id bigint,
    p_nombre varchar,
    p_direccion text,
    p_zona_id bigint,
    p_latitud numeric,
    p_longitud numeric,
    p_capacidad_total integer,
    p_ocupacion_actual integer,
    p_estado varchar,
    p_responsable_id bigint,
    p_telefono_contacto varchar,
    p_observaciones text
) as $$
begin
    update refugio
    set nombre = p_nombre,
        direccion = p_direccion,
        zona_id = p_zona_id,
        latitud = p_latitud,
        longitud = p_longitud,
        capacidad_total = p_capacidad_total,
        ocupacion_actual = p_ocupacion_actual,
        estado = p_estado,
        responsable_id = p_responsable_id,
        telefono_contacto = p_telefono_contacto,
        observaciones = p_observaciones,
        updated_at = now()
    where id = p_id and activo = true;
end;
$$ language plpgsql;

