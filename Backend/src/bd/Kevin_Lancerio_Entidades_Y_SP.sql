-- actualizar asignacion de recurso
create or replace procedure sp_actualizar_asignacion_recurso(
    p_id bigint,
    p_cantidad integer,
    p_estado varchar,
    p_fecha_asignacion timestamptz default null,
    p_fecha_entrega timestamptz default null,
    p_observaciones text default null
) as $$
begin
    update asignacion_recurso
    set cantidad = p_cantidad,
        estado = p_estado,
        fecha_asignacion = coalesce(p_fecha_asignacion, fecha_asignacion),
        fecha_entrega = coalesce(p_fecha_entrega, fecha_entrega),
        observaciones = coalesce(p_observaciones, observaciones),
        updated_at = now()
    where id = p_id;
end;
$$ language plpgsql;

