-- tabla refugio
create table refugio (
    id bigint generated by default as identity primary key,
    nombre varchar(160) not null,
    direccion text,
    zona_id bigint references zona(id),
    latitud numeric(9,6),
    longitud numeric(9,6),
    capacidad_total integer not null check (capacidad_total >= 0),
    ocupacion_actual integer not null default 0 check (ocupacion_actual >= 0),
    estado varchar(20) not null default 'DISPONIBLE'
        check (estado in ('DISPONIBLE', 'PARCIAL', 'LLENO', 'INACTIVO')),
    responsable_id bigint references usuario(id),
    telefono_contacto varchar(30),
    observaciones text,
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz,
    constraint refugio_ocupacion_max check (ocupacion_actual <= capacidad_total)
);

-- tabla recurso
create table recurso (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    tipo varchar(30) not null
        check (tipo in ('AGUA', 'ALIMENTO', 'MEDICAMENTO', 'EQUIPO', 'VEHICULO', 'OTRO')),
    unidad_medida varchar(30) not null default 'UNIDAD'
        check (unidad_medida in ('UNIDAD', 'CAJA', 'KILOGRAMO', 'LITRO', 'PERSONA', 'OTRO')),
    cantidad_total integer not null default 0 check (cantidad_total >= 0),
    descripcion text,
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz
);

-- tabla asignacion_recurso
create table asignacion_recurso (
    id bigint generated by default as identity primary key,
    recurso_id bigint not null references recurso(id),
    incidente_id bigint references incidente(id),
    refugio_id bigint references refugio(id),
    cantidad integer not null check (cantidad > 0),
    estado varchar(30) not null default 'SOLICITADO'
        check (estado in ('SOLICITADO', 'ASIGNADO', 'ENVIADO', 'ENTREGADO', 'CANCELADO')),
    fecha_solicitud timestamptz not null default now(),
    fecha_asignacion timestamptz,
    fecha_entrega timestamptz,
    usuario_asigna_id bigint references usuario(id),
    observaciones text,
    created_at timestamptz not null default now(),
    updated_at timestamptz,
    constraint asignacion_recurso_destino check (
        (incidente_id is not null and refugio_id is null)
        or
        (incidente_id is null and refugio_id is not null)
    )
);

-- listar todos los refugios activos
create or replace function sp_listar_refugios()
returns table (
    id bigint,
    nombre varchar,
    direccion text,
    zona_id bigint,
    latitud numeric,
    longitud numeric,
    capacidad_total integer,
    ocupacion_actual integer,
    estado varchar,
    responsable_id bigint,
    telefono_contacto varchar,
    activo boolean,
    created_at timestamptz
) as $$
begin
    return query
    select r.id, r.nombre, r.direccion, r.zona_id, r.latitud, r.longitud,
           r.capacidad_total, r.ocupacion_actual, r.estado, r.responsable_id,
           r.telefono_contacto, r.activo, r.created_at
    from refugio r
    where r.activo = true
    order by r.nombre;
end;
$$ language plpgsql;

-- agregar nuevo refugio
create or replace procedure sp_agregar_refugio(
    p_nombre varchar,
    p_capacidad_total integer,
    p_direccion text default null,
    p_zona_id bigint default null,
    p_latitud numeric default null,
    p_longitud numeric default null,
    p_responsable_id bigint default null,
    p_telefono_contacto varchar default null
) as $$
begin
    insert into refugio (nombre, direccion, zona_id, latitud, longitud, 
                        capacidad_total, responsable_id, telefono_contacto)
    values (p_nombre, p_direccion, p_zona_id, p_latitud, p_longitud,
            p_capacidad_total, p_responsable_id, p_telefono_contacto);
end;
$$ language plpgsql;

-- buscar refugio por id
create or replace function sp_buscar_refugio(p_id bigint)
returns table (
    id bigint,
    nombre varchar,
    direccion text,
    zona_id bigint,
    latitud numeric,
    longitud numeric,
    capacidad_total integer,
    ocupacion_actual integer,
    estado varchar,
    responsable_id bigint,
    telefono_contacto varchar,
    observaciones text,
    activo boolean,
    created_at timestamptz,
