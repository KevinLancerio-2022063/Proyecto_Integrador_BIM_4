-- listar todos los usuarios activos
create or replace function sp_listar_usuarios()
returns table (
    id bigint,
    nombre varchar(120),
    email varchar(160),
    telefono varchar(30),
    rol varchar(30),
    activo boolean,
    habilidades text,
    disponible boolean,
    created_at timestamptz
) as $$
begin
    return query
    select u.id, u.nombre, u.email, u.telefono, u.rol, u.activo, 
