-- tabla usuario
create table usuario (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    email varchar(160) not null unique,
    password_hash varchar(255) not null,
    telefono varchar(30),
    rol varchar(30) not null default 'VOLUNTARIO'
        check (rol in ('ADMIN', 'COORDINADOR', 'RESCATISTA', 'VOLUNTARIO', 'GESTOR_REFUGIO')),
    activo boolean not null default true,
    habilidades text,
    disponible boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz
);

-- tabla zona
create table zona (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    municipio varchar(120),
    departamento varchar(120),
    pais varchar(80) not null default 'Guatemala',
    latitud numeric(9,6),
    longitud numeric(9,6),
    nivel_riesgo varchar(20) not null default 'MEDIO'
        check (nivel_riesgo in ('BAJO', 'MEDIO', 'ALTO', 'CRITICO')),
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz
);

-- tabla incidente
create table incidente (
    id bigint generated by default as identity primary key,
    tipo varchar(40) not null
        check (tipo in ('INUNDACION', 'TERREMOTO', 'INCENDIO', 'DESLIZAMIENTO', 'ACTIVIDAD_VOLCANICA', 'OTRO')),
    titulo varchar(160) not null,
    descripcion text,
    nivel_emergencia varchar(20) not null default 'MEDIA'
        check (nivel_emergencia in ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    estado varchar(30) not null default 'REPORTADO'
        check (estado in ('REPORTADO', 'EN_ATENCION', 'MITIGADO', 'CERRADO')),
    fecha_reporte timestamptz not null default now(),
    fecha_cierre timestamptz,
    zona_id bigint not null references zona(id),
    reportado_por bigint not null references usuario(id),
    latitud numeric(9,6),
    longitud numeric(9,6),
    cantidad_personas_afectadas integer check (cantidad_personas_afectadas >= 0),
    observaciones text,
    created_at timestamptz not null default now(),
    updated_at timestamptz
);

-- tabla refugio
create table refugio (
    id bigint generated by default as identity primary key,
    nombre varchar(160) not null,
    direccion text,
    zona_id bigint references zona(id),
    latitud numeric(9,6),
    longitud numeric(9,6),
    capacidad_total integer not null check (capacidad_total >= 0),
    ocupacion_actual integer not null default 0 check (ocupacion_actual >= 0),
    estado varchar(20) not null default 'DISPONIBLE'
        check (estado in ('DISPONIBLE', 'PARCIAL', 'LLENO', 'INACTIVO')),
    responsable_id bigint references usuario(id),
    telefono_contacto varchar(30),
    observaciones text,
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz,
    constraint refugio_ocupacion_max check (ocupacion_actual <= capacidad_total)
);

-- tabla recurso
create table recurso (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    tipo varchar(30) not null
        check (tipo in ('AGUA', 'ALIMENTO', 'MEDICAMENTO', 'EQUIPO', 'VEHICULO', 'OTRO')),
    unidad_medida varchar(30) not null default 'UNIDAD'
        check (unidad_medida in ('UNIDAD', 'CAJA', 'KILOGRAMO', 'LITRO', 'PERSONA', 'OTRO')),
    cantidad_total integer not null default 0 check (cantidad_total >= 0),
    descripcion text,
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz
);

-- tabla asignacion_recurso
create table asignacion_recurso (
    id bigint generated by default as identity primary key,
    recurso_id bigint not null references recurso(id),
    incidente_id bigint references incidente(id),
    refugio_id bigint references refugio(id),
    cantidad integer not null check (cantidad > 0),
    estado varchar(30) not null default 'SOLICITADO'
        check (estado in ('SOLICITADO', 'ASIGNADO', 'ENVIADO', 'ENTREGADO', 'CANCELADO')),
    fecha_solicitud timestamptz not null default now(),
    fecha_asignacion timestamptz,
    fecha_entrega timestamptz,
    usuario_asigna_id bigint references usuario(id),
    observaciones text,
    created_at timestamptz not null default now(),
    updated_at timestamptz,
    constraint asignacion_recurso_destino check (
        (incidente_id is not null and refugio_id is null)
        or
        (incidente_id is null and refugio_id is not null)
    )
);

-- tabla asignacion_personal
create table asignacion_personal (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null references usuario(id),
    incidente_id bigint references incidente(id),
    refugio_id bigint references refugio(id),
    rol_asignado varchar(30) not null default 'APOYO'
        check (rol_asignado in ('COORDINACION', 'RESCATE', 'APOYO', 'LOGISTICA', 'GESTION_REFUGIO')),
    estado varchar(30) not null default 'ASIGNADO'
        check (estado in ('ASIGNADO', 'EN_CAMINO', 'ACTIVO', 'FINALIZADO', 'CANCELADO')),
    fecha_asignacion timestamptz not null default now(),
    fecha_finalizacion timestamptz,
    observaciones text,
    created_at timestamptz not null default now(),
    updated_at timestamptz,
    constraint asignacion_personal_destino check (
        (incidente_id is not null and refugio_id is null)
        or
        (incidente_id is null and refugio_id is not null)
    )
);

-- tabla alerta
create table alerta (
    id bigint generated by default as identity primary key,
    incidente_id bigint references incidente(id),
    zona_id bigint references zona(id),
    refugio_id bigint references refugio(id),
    tipo varchar(30) not null
        check (tipo in ('EMERGENCIA', 'RECURSO', 'REFUGIO', 'SEGUIMIENTO', 'OTRO')),
    nivel varchar(20) not null
        check (nivel in ('INFO', 'ADVERTENCIA', 'CRITICA')),
    mensaje text not null,
    estado varchar(20) not null default 'ACTIVA'
        check (estado in ('ACTIVA', 'LEIDA', 'RESUELTA')),
    fecha timestamptz not null default now(),
    constraint alerta_destino check (
        incidente_id is not null
        or zona_id is not null
        or refugio_id is not null
    )
);

-- tabla historial_incidente
create table historial_incidente (
    id bigint generated by default as identity primary key,
    incidente_id bigint not null references incidente(id),
    estado_anterior varchar(30),
    estado_nuevo varchar(30) not null
        check (estado_nuevo in ('REPORTADO', 'EN_ATENCION', 'MITIGADO', 'CERRADO')),
    comentario text,
    usuario_id bigint references usuario(id),
    fecha timestamptz not null default now()
);


